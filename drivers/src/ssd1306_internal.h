#ifndef I2C_TEST_SSD1306_INTERNAL_H
#define I2C_TEST_SSD1306_INTERNAL_H

#include <stdbool.h>
#include <stdint.h>
#include <i2c.h>
#include <ssd1306.h>

#define SSD1306_TARGET_ADDRESS (0x3C)

#define SSD1306_CMD_CONTINUATION_BIT (7)
#define SSD1306_CMD_CONTINUATION (1U << (SSD1306_CMD_CONTINUATION_BIT))
#define SSD1306_DC_SELECTION_BIT (6)
#define SSD1306_DATA_SELECTION (1U << (SSD1306_DC_SELECTION_BIT))
#define SSD1306_CTRL_BYTE (0x00)

#define SSD1306_CMD_CHARGE_PUMP (0x8D)
#define SSD1306_DATA_CHARGE_PUMP_BIT (2)
#define SSD1306_DATA_CHARGE_PUMP(enabled) (0x10 | !!(enabled) << SSD1306_DATA_CHARGE_PUMP_BIT)

#define SSD1306_CMD_SET_DISPLAY_BIT (0)
#define SSD1306_CMD_SET_DISPLAY(enabled) (0xAE | !!(enabled) << SSD1306_CMD_SET_DISPLAY_BIT)

#define SSD1306_CMD_SET_PAGE_START_BITS (0x7)
#define SSD1306_CMD_SET_PAGE_START(page) (0xB0 | ((SSD1306_CMD_SET_PAGE_START_BITS) & (page)))

#define SSD1306_CMD_SET_LOWER_COL_START_BITS (0xF)
#define SSD1306_CMD_SET_LOWER_COL_START(val) (0x00 | ((SSD1306_CMD_SET_LOWER_COL_START_BITS) & (val)))

#define SSD1306_CMD_SET_HIGHER_COL_START_BITS (0xF)
#define SSD1306_CMD_SET_HIGHER_COL_START(val) (0x10 | ((SSD1306_CMD_SET_HIGHER_COL_START_BITS) & (val)))

#define SSD1306_PAGE_HEADER_PAGE_START_INDEX (1)

#endif // I2C_TEST_SSD1306_INTERNAL_H
